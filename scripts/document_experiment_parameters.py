"""Inventory the saved configurations behind every row of the current comparison.

Only small configuration and result metadata are read. Neural weight tensors
are indexed by path and existing recorded digest, rather than loaded or copied.
"""
import csv
import hashlib
import json
from pathlib import Path
import re
import sys

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from scripts.experiment_labels import method_label

from scripts.paper.archive_paths import optional_source_root, optional_output_root
ROOT = optional_source_root(Path(__file__).resolve().parents[1])
OUT = optional_output_root(ROOT / "docs/experiment_parameters_20261014")
SOURCES = {}
RECORDS = []
WEIGHTS = []
SEARCHES = []


def read(path):
    path = Path(path)
    if not path.is_absolute():
        path = ROOT / path
    raw = path.read_bytes()
    SOURCES[str(path.relative_to(ROOT))] = hashlib.sha256(raw).hexdigest()
    return yaml.safe_load(raw) if path.suffix in (".yaml", ".yml") else json.loads(raw)


def csv_rows(path):
    path = Path(path)
    if not path.is_absolute():
        path = ROOT / path
    raw = path.read_bytes()
    SOURCES[str(path.relative_to(ROOT))] = hashlib.sha256(raw).hexdigest()
    return list(csv.DictReader(raw.decode().splitlines()))


def add(record_id, family, dataset, tokenizer, method, parameters, config_sources, checkpoint=None, note=""):
    RECORDS.append(dict(id=record_id, family=family, dataset=dataset, tokenizer=tokenizer,
                        method=method, display_method=method_label(method), parameters=parameters, config_sources=config_sources,
                        checkpoint=checkpoint, note=note))
    return record_id


def flat(value, prefix=""):
    if isinstance(value, dict):
        for key, child in value.items():
            yield from flat(child, prefix + "." + str(key) if prefix else str(key))
    else:
        yield prefix, value


def write_csv(name, rows):
    with (OUT / name).open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def write_selected_settings():
    """Readable per-case values, kept in sync with the complete inventory."""
    labels = {"amazon-beauty": "Beauty", "amazon-sports": "Sports",
              "amazon-toys": "Toys", "amazon-pet-supplies": "Pet Supplies"}
    tokenizers = {"rkmeans": "RKMeans", "rvq": "RVQ", "rqvae": "RQ-VAE"}
    cases = [(d, t) for d in labels for t in tokenizers]
    lines = ["# Selected settings for all dataset–tokenizer cases — historical comparison and pilot", "",
             "The historical tables below were generated by `scripts/document_experiment_parameters.py` from saved configurations for the 14 October comparison. "
             "A separately audited 15 October pilot addendum follows; its checkpoints and weights are not in the historical CSV/JSON companions. "
             "Historical numeric values are displayed to 12 significant digits; their JSON/CSV companions retain the recorded precision. "
             "Pilot values retain full precision in the linked run configurations.", "",
             "## Historical source generator and fine-tuning checkpoints", "",
             "Local updates count from the source checkpoint. Update 0 selects that source checkpoint. "
             "Exact paths and available recorded digests are in [checkpoint_index.csv](checkpoint_index.csv).", "",
             "| Dataset | Tokenizer | Source checkpoint | Standard fine-tuning update | IFairLRS RW update | SPRINT update |",
             "|---|---|---|---:|---:|---:|"]
    for d, t in cases:
        source = next(r for r in RECORDS if r["family"] == "grid_original" and (r["dataset"], r["tokenizer"]) == (d, t))
        local = [r for r in RECORDS if r["family"] == "local_continuation" and (r["dataset"], r["tokenizer"]) == (d, t)]
        updates = [next(r["parameters"]["selected_update"] for r in local if r["parameters"]["run"]["mode"] == m) for m in ("ordinary", "rw", "sprint")]
        lines.append(f"| {labels[d]} | {tokenizers[t]} | `{Path(source['checkpoint']['path']).name}` | " + " | ".join(map(str, updates)) + " |")
    lines += ["", "## Validation-selected reranking", "",
              "CPFair and P-MMF strengths are the applied values for the reported tests. "
              "RR's floor is epsilon in the frozen correction. "
              "The applied values match the minimum declared fairness loss within a 5% validation Recall@5 loss budget. "
              "Beauty RKMeans CPFair/P-MMF values were verified from their earlier sweep/test artifacts; "
              "later RR manifest placeholders are not their applied settings.", "",
              "| Dataset | Tokenizer | RR alpha | RR floor | CPFair lambda | P-MMF lambda |",
              "|---|---|---:|---:|---:|---:|"]
    for d, t in cases:
        selected = {r["parameters"]["applied_method"]: r["parameters"]["applied_parameters"] for r in RECORDS
                    if r["family"] == "reranking" and (r["dataset"], r["tokenizer"]) == (d, t)}
        lines.append(f"| {labels[d]} | {tokenizers[t]} | {selected['rr']['alpha']} | {selected['rr']['floor']} | {selected['cpfair']['lambda']} | {selected['pmmf']['lambda']} |")
    for method, title in (("IFairLRS RW", "Historical IFairLRS training weights"), ("RR correction", "Frozen RR popularity corrections")):
        lines += ["", "## " + title, "", "Groups 0–4 run from lower to higher training popularity. "
                  "RR corrections are signed group corrections, not neural training loss multipliers.", "",
                  "| Dataset | Tokenizer | Group 0 | Group 1 | Group 2 | Group 3 | Group 4 |",
                  "|---|---|---:|---:|---:|---:|---:|"]
        for d, t in cases:
            weights = {str(r["group"]): r["weight"] for r in WEIGHTS if (r["dataset"], r["tokenizer"], r["method"]) == (d, t, method)}
            assert set(weights) == set(map(str, range(5)))
            lines.append(f"| {labels[d]} | {tokenizers[t]} | " + " | ".join(f"{weights[str(g)]:.12g}" for g in range(5)) + " |")
    lines += ["", "The full tested parameter combinations, including zero-strength active settings, "
              "are in [reranking_search_spaces.csv](reranking_search_spaces.csv). "
              "The untreated `{}` configuration is recorded separately in the source sweeps.", ""]
    # The pilot is an independently audited, dated supplement to this inventory.
    # Rebuilding the historical tables must preserve that existing evidence.
    destination = OUT / "selected_settings.md"
    existing = destination.read_text() if destination.exists() else ""
    marker = "\n## Joint-fairness pilot addendum"
    supplement = existing[existing.index(marker):] if marker in existing else ""
    destination.write_text("\n".join(lines) + supplement)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    table_path = ROOT / "docs/rq2_comparison_draft_20261011/comparison_results.csv"
    rows = csv_rows(table_path)
    rkmeans_audit_path = "docs/rkmeans_reranking_analysis_20261011/test_results.csv"
    rkmeans_audit = csv_rows(rkmeans_audit_path)
    provenance = read("docs/rq2_comparison_draft_20261011/provenance.json")
    groups = {}
    for r in rows:
        groups.setdefault((r["dataset"], r["tokenizer"], r["method"]), []).append(r)
    training = {(r["dataset"], r["tokenizer"], r["method"]): r for r in provenance["training_runs"]}
    local = {(r["dataset"], r["tokenizer"], r["method"]): r for r in provenance["local_training_branches"]}
    ordinary = {(r["dataset"], r["tokenizer"], "GRID: ordinary continuation"): r for r in provenance["ordinary_continuations"]}
    native_seen, tokenizer_seen, rr_seen = set(), set(), set()
    index = []
    for dataset in sorted({r["dataset"] for r in rows}):
        folder = ROOT / "recommendation/processed_dataset" / dataset
        parameters = {name: read(folder / name) for name in ("dataset_stats.json", "process_config.yaml", "grid_data_manifest.json", "user_activity_metadata.json")}
        add("data:" + dataset, "dataset", dataset, "", "preprocessing", parameters,
            [str((folder / name).relative_to(ROOT)) for name in parameters])
        source_name = dataset.removeprefix("amazon-").replace("-", "_")
        split_path = f"GRID/data/amazon_{source_name}_5core_tfrecords/temporal_loo/complete_metadata/split_config.json"
        embedding_path = f"GRID/outputs/{source_name}_5core/temporal_loo/complete_metadata/common/step1_embeddings/.hydra/config.yaml"
        add("embedding:" + dataset, "native_embedding", dataset, "", "item embeddings",
            dict(embedding=read(embedding_path), source_split=read(split_path)),
            [embedding_path, split_path], note="Embedding inference only; inherited trainer budgets are not training steps.")
    for (dataset, tokenizer, method), metric_rows in groups.items():
        assert sorted(int(r["k"]) for r in metric_rows) == [5, 10, 20]
        source = metric_rows[0]["source"]
        assert all(r["source"] == source for r in metric_rows)
        key = dataset, tokenizer, method
        rid = ":".join(key)
        config_sources = []
        if key in training:
            path = training[key]["config"]
            params = read(path)
            checkpoint_path = ROOT / Path(path).parent / "best_model.pth"
            checkpoint = dict(path=str(checkpoint_path.relative_to(ROOT)), exists=checkpoint_path.exists(),
                              recorded_sha256=provenance["sources"].get(str(checkpoint_path.relative_to(ROOT))))
            add(rid, "fairdiverse_training", dataset, tokenizer, method, params, [path], checkpoint,
                "Saved training-run configuration; result is a recorded FairDiverse evaluation.")
        elif method in ("SASRec", "GRU4Rec"):
            report = read(source)
            case = report["case"]
            add(rid, "classic", dataset, "", method,
                dict(training=case["config"], evaluation_protocol=report["protocol"],
                     scoring_method=report.get("score_method", "gemm"), config_origin=case["config_origin"]),
                [str(Path(case["config_reference"]["path"]).relative_to(ROOT)), source], case["checkpoint"],
                case["historical_training_provenance"])
        elif key in local or key in ordinary:
            record = (local if key in local else ordinary)[key]
            continuation = record.get("continuation", str(Path(record["source"]).parent / "continuation.json"))
            if not (ROOT / continuation).exists():
                continuation = next(r["ordinary_control"] for r in provenance["local_training_branches"]
                                    if r["dataset"] == dataset and r["tokenizer"] == tokenizer)
            completion = read(continuation)
            run_path = str(Path(continuation).parent / "run_config.json")
            params = read(run_path)
            add(rid, "local_continuation", dataset, tokenizer, method,
                dict(run=params, selected_update=completion["selected_update"],
                     selection_metric=completion["selection_metric"], selection_policy=completion["selection_policy"],
                     training_examples=completion["training_examples"],
                     control_improvement_required=params.get("control_improvement_required", record.get("control_improvement_required", True))),
                [run_path, continuation], completion["selected_checkpoint"])
            if params.get("rw_statistics"):
                for group, weight in params["rw_statistics"]["weights"].items():
                    WEIGHTS.append(dict(dataset=dataset, tokenizer=tokenizer, method="IFairLRS RW",
                                        group_type="popularity", group=group, weight=weight,
                                        source=run_path, definition="training-history share / training-target share"))
        elif method == "GRID: original (fresh evaluation)":
            report = read(source)
            if "case" in report:
                case = report["case"]
                export_path = case["config"]["path"]
                checkpoint = case["checkpoint"]
            else:
                metadata = report["input_metadata"]
                export_path = metadata["provenance"]["export_config"]["path"]
                checkpoint = metadata["checkpoint"]
            export = read(export_path)
            add(rid, "grid_original", dataset, tokenizer, method, export,
                [str(Path(export_path).relative_to(ROOT))], checkpoint,
                "Fresh evaluation of the original source checkpoint; evaluated before the later standard fine-tuning control.")
            native_path = Path(checkpoint["path"]).parent.parent / ".hydra/config.yaml"
            tok_path = Path(checkpoint["path"]).parents[2] / "step2_tokenizer_training/.hydra/config.yaml"
            for path, seen, family in ((native_path, native_seen, "native_generator"),
                                       (tok_path, tokenizer_seen, "native_tokenizer")):
                if path not in seen:
                    seen.add(path)
                    config = read(path)
                    extra_sources = []
                    native_checkpoint = checkpoint if family == "native_generator" else None
                    if family == "native_tokenizer":
                        inference_path = path.parents[2] / "step2b_sid_inference/.hydra/config.yaml"
                        inference = read(inference_path)
                        config["sid_inference_export_config"] = inference
                        extra_sources.append(str(inference_path.relative_to(ROOT)))
                        tokenizer_checkpoint = Path(inference["ckpt_path"])
                        native_checkpoint = dict(path=str(tokenizer_checkpoint), exists=tokenizer_checkpoint.exists())
                    add(f"{family}:{dataset}:{tokenizer}", family, dataset, tokenizer,
                        family, config, [str(path.relative_to(ROOT))] + extra_sources, native_checkpoint,
                        "Saved Hydra configuration; interpolation expressions are preserved verbatim.")
        elif method in ("GRID: saved reranking reference", "GRID + RR", "GRID + CPFair", "GRID + P-MMF"):
            rr_source = groups[dataset, tokenizer, "GRID + RR"][0]["source"]
            if Path(rr_source).suffix == ".csv":
                labels = {"amazon-beauty": "Beauty", "amazon-sports": "Sports", "amazon-toys": "Toys", "amazon-pet-supplies": "Pet Supplies"}
                rr_source = next(r["source"] for r in csv_rows(rr_source)
                                 if r["dataset"] == labels[dataset] and r["method"] == "RR" and r["k"] == "5")
            folder = Path(rr_source).parent
            selection_path = str(folder / "selection.json")
            selection = read(selection_path)
            correction_path = str(folder / "rr_correction.json")
            correction = read(correction_path)
            method_key = {"GRID: saved reranking reference": "control", "GRID + RR": "rr", "GRID + CPFair": "cpfair", "GRID + P-MMF": "pmmf"}[method]
            config_sources = [selection_path, correction_path]
            selected = selection.get("validation_selection", {}).get("selections", {}).get(method_key)
            legacy_backend = None
            if method_key == "control":
                applied = {}
            elif selected:
                applied = selected["parameters"]
                sweep_path = selected["rows"]["path"]
            else:
                # Beauty RKMeans CPFair/P-MMF predate the automatic RR manifest.
                # Its zero placeholders do not describe these reported tests.
                assert (dataset, tokenizer) == ("amazon-beauty", "rkmeans")
                assert method_key in ("cpfair", "pmmf")
                audit = next(r for r in rkmeans_audit if r["dataset"] == "Beauty" and
                             r["method"] == ("CPFair" if method_key == "cpfair" else "P-MMF") and r["k"] == "5")
                applied = json.loads(audit["parameters"])
                config_sources.append(rkmeans_audit_path)
                # These historical dense-backend reports put the first cutoff's
                # configuration before the large rankings. Read a bounded prefix.
                with (ROOT / audit["source"]).open() as stream:
                    prefix = stream.read(131072)
                match = re.search(r'"config"\s*:\s*', prefix)
                assert match is not None
                legacy_backend, _ = json.JSONDecoder().raw_decode(prefix, match.end())
                assert legacy_backend["backend_config"]["lambda"] == applied["lambda"]
                config_sources.append(audit["source"])
                suffix = "351961" if method_key == "cpfair" else "351975"
                sweep_path = f"additional_baselines/artifacts/beauty_{method_key}_validation_tuning_{suffix}/validation_tradeoff.csv"
            if method_key != "control":
                sweep = csv_rows(sweep_path)
                tested = sorted({r["parameters"] for r in sweep if int(r["k"]) == 5 and r["parameters"] != "{}"})
                assert json.dumps(applied, sort_keys=True) in {json.dumps(json.loads(p), sort_keys=True) for p in tested}
                SEARCHES.append(dict(dataset=dataset, tokenizer=tokenizer, method=method_key,
                                     selected=json.dumps(applied, sort_keys=True),
                                     tested_parameters=json.dumps([json.loads(p) for p in tested]),
                                     selection_k=5, max_relative_recall_loss=.05,
                                     source=str(Path(sweep_path).relative_to(ROOT)) if Path(sweep_path).is_absolute() else sweep_path))
                config_sources.append(SEARCHES[-1]["source"])
            params = dict(selection=selection, rr_frozen_correction=correction if method_key == "rr" else None,
                          candidate_identity=correction["validation_metadata"],
                          legacy_backend_config=legacy_backend,
                          applied_method=method_key, applied_parameters=applied,
                          backend=dict(group="brand" if method_key in ("cpfair", "pmmf") else "popularity" if method_key == "rr" else None,
                                       learning_rate=.5 if method_key == "pmmf" else None,
                                       gamma=.2 if method_key == "pmmf" else None,
                                       provider_weights="all catalog brands have weight 1.0, without normalization" if method_key == "pmmf" else None,
                                       matrix_mode="legacy_dense" if legacy_backend else "lookup", order_seed=None,
                                       projection=(selection.get("validation_selection", {}).get("projection", "unchanged CVXPY default solver")
                                                   if method_key == "pmmf" else None),
                                       cutoff_state_reset=True))
            note = "Settings selected on validation; test uses matched saved candidates and no model fine-tuning."
            if not selected and method_key != "control":
                note += " Applied parameters come from the earlier verified test audit; unrelated RR manifest fields are placeholders."
            add(rid, "reranking", dataset, tokenizer, method, params, config_sources,
                correction["validation_metadata"]["checkpoint"],
                note)
            if (dataset, tokenizer) not in rr_seen:
                rr_seen.add((dataset, tokenizer))
                for group, weight in correction["punishment"].items():
                    WEIGHTS.append(dict(dataset=dataset, tokenizer=tokenizer, method="RR correction",
                                        group_type="popularity", group=group, weight=weight,
                                        source=correction_path, definition="normalized validation popularity correction"))
        else:
            raise ValueError("Unmapped comparison row: " + str(key))
        index.append(dict(dataset=dataset, tokenizer=tokenizer, method=method_label(method), source_method=method,
                          parameter_record=rid, metrics_source=source,
                          evaluation_status=metric_rows[0]["status"]))
    assert len(index) == len(groups) == 188
    parameters = []
    checkpoints = []
    for record in RECORDS:
        for key, value in flat(record["parameters"]):
            parameters.append(dict(record=record["id"], family=record["family"], dataset=record["dataset"],
                                   tokenizer=record["tokenizer"], method=record["display_method"], parameter=key,
                                   value=json.dumps(value, ensure_ascii=False, default=str)))
        if record["checkpoint"]:
            checkpoint = record["checkpoint"]
            checkpoints.append(dict(record=record["id"], family=record["family"], dataset=record["dataset"],
                                    tokenizer=record["tokenizer"], method=record["display_method"],
                                    path=checkpoint["path"], sha256=checkpoint.get("sha256", checkpoint.get("recorded_sha256")),
                                    hash_status="existing recorded digest" if checkpoint.get("sha256", checkpoint.get("recorded_sha256")) else "not recorded in controlling provenance"))
    write_csv("run_index.csv", index)
    write_csv("parameter_values.csv", parameters)
    write_csv("group_weights.csv", WEIGHTS)
    write_csv("reranking_search_spaces.csv", SEARCHES)
    write_csv("checkpoint_index.csv", checkpoints)
    write_selected_settings()
    implementation_paths = ["fairdiverse/recommendation/trainer.py", "fairdiverse/recommendation/base_model/grid_model.py",
                            "fairdiverse/recommendation/base_model/sasrec.py", "fairdiverse/recommendation/base_model/gru4rec.py",
                            "additional_baselines/continuation_grid.py", "additional_baselines/sprint_grid.py",
                            "additional_baselines/ifairlrs.py", "additional_baselines/rerank/fairdiverse.py",
                            "additional_baselines/rerank/fast_pmmf.py", "scripts/rq2_classic_evaluation.py",
                            "GRID/src/modules/clustering/residual_quantization.py"]
    implementation_paths += [f"fairdiverse/recommendation/rank_model/{m}.py" for m in ("APR", "IPS", "Minmax_SGD", "SDRO", "FOCF", "Reg", "FairDual")]
    implementation_hashes = {path: hashlib.sha256((ROOT / path).read_bytes()).hexdigest() for path in implementation_paths}
    (OUT / "parameter_inventory.json").write_text(json.dumps(dict(
        date="2026-10-14", scope="All 188 logical result rows in the current four-dataset, three-tokenizer comparison",
        records=RECORDS, source_sha256=SOURCES, current_implementation_sha256=implementation_hashes,
        completeness=dict(comparison_rows=len(index), records=len(RECORDS), parameter_values=len(parameters),
                          group_weights=len(WEIGHTS), checkpoint_references=len(checkpoints)),
        limits=["Saved configuration values are distinguished from confirmed effective code paths in the companion documentation",
                "Historical Hydra interpolation strings remain unresolved in raw snapshots",
                "Existing checkpoint hashes are indexed; neural tensors are not loaded, copied, or freshly rehashed",
                "Per-minibatch dynamic fairness states are not reconstructed"]), indent=2, default=str) + "\n")
    print(json.dumps({"records": len(RECORDS), "comparison_rows": len(index),
                      "parameter_values":len(parameters), "group_weights":len(WEIGHTS), "output":str(OUT)},indent=2))


if __name__ == "__main__":
    main()
