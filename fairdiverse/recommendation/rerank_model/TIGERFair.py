"""Exposure-aware reranking for generative recommendation candidates.

The reranker is deliberately post-hoc: it never invents items that were not
generated by TIGER/GRID.  It trades candidate relevance against the current
amortized exposure deficit of each provider/popularity group.
"""

import json
import math

import numpy as np
from tqdm import trange

from .Abstract_Reranker import Abstract_Reranker


class TIGERFair(Abstract_Reranker):
    """Greedy, position-aware max-min exposure reranker.

    Required inputs are the usual FairDiverse ``ranking_score`` matrix and the
    item-to-group mapping loaded by :class:`Abstract_Reranker`.  Scores at or
    below ``invalid_score_threshold`` are treated as items outside the
    generative candidate set and can never be selected.
    """

    def __init__(self, config, weights=None):
        super().__init__(config, weights)
        self.last_exposure = np.zeros(self.group_num, dtype=np.float64)

    def _target_distribution(self, candidate_groups):
        explicit_target = self.config.get("target_exposure")
        if explicit_target is not None:
            target = np.asarray(explicit_target, dtype=np.float64)
            if target.shape != (self.group_num,):
                raise ValueError(
                    "target_exposure must contain one value per group "
                    f"({self.group_num}), got {target.size}"
                )
        elif self.config.get("target_distribution", "uniform") == "catalog":
            target = np.asarray(self.M.sum(axis=0), dtype=np.float64)
        elif self.config.get("target_distribution", "uniform") == "uniform":
            target = np.ones(self.group_num, dtype=np.float64)
        else:
            raise ValueError(
                "target_distribution must be 'uniform' or 'catalog', or "
                "target_exposure must be supplied"
            )

        # A generator cannot allocate exposure to a group absent from every
        # candidate list. Excluding such groups avoids an impossible target.
        available = np.zeros(self.group_num, dtype=bool)
        if candidate_groups.size:
            available[np.unique(candidate_groups)] = True
        target = np.where(available, target, 0.0)
        if np.any(target < 0) or not np.all(np.isfinite(target)):
            raise ValueError("target exposure values must be finite and non-negative")
        total = target.sum()
        if total <= 0:
            raise ValueError("no positive target mass remains for generated candidates")
        target = target / total
        self.last_candidate_group_coverage = float(np.mean(available))
        self.last_target = target.copy()
        return target

    def _load_initial_exposure(self):
        value = self.config.get("initial_exposure")
        path = self.config.get("historical_exposure_path")
        if value is not None and path is not None:
            raise ValueError(
                "configure only one of initial_exposure and historical_exposure_path"
            )
        if path is not None:
            if path.endswith(".npy"):
                value = np.load(path)
            else:
                with open(path, "r", encoding="utf-8") as stream:
                    payload = json.load(stream)
                if isinstance(payload, dict):
                    # Accept either {group: exposure} or FairDiverse's
                    # {"top@K": "[... ]"} output when a key is configured.
                    key = self.config.get("historical_exposure_key")
                    if key is not None:
                        payload = payload[key]
                        if isinstance(payload, str):
                            payload = json.loads(payload)
                    else:
                        value = np.zeros(self.group_num, dtype=np.float64)
                        for group, exposure in payload.items():
                            value[int(group)] = float(exposure)
                if value is None:
                    value = payload

        if value is None:
            return np.zeros(self.group_num, dtype=np.float64)
        exposure = np.asarray(value, dtype=np.float64)
        if exposure.shape != (self.group_num,):
            raise ValueError(
                "initial exposure must contain one value per group "
                f"({self.group_num}), got {exposure.size}"
            )
        if np.any(exposure < 0) or not np.all(np.isfinite(exposure)):
            raise ValueError("initial exposure values must be finite and non-negative")
        history_weight = float(self.config.get("historical_exposure_weight", 1.0))
        if history_weight < 0 or not np.isfinite(history_weight):
            raise ValueError("historical_exposure_weight must be finite and non-negative")
        return exposure * history_weight

    def _candidate_items(self, scores, candidate_size, invalid_threshold):
        valid = np.flatnonzero(np.isfinite(scores) & (scores > invalid_threshold))
        if candidate_size is not None and valid.size > candidate_size:
            keep = np.argpartition(scores[valid], -candidate_size)[-candidate_size:]
            valid = valid[keep]
        # Stable ordering makes ties reproducible and lambda=0 match the base
        # ranker (higher item ID wins exactly as argsort(...)[::-1]).
        return valid[np.lexsort((-valid, -scores[valid]))]

    def _normalise_relevance(self, scores):
        mode = self.config.get("relevance_normalization", "minmax")
        if mode == "none":
            return scores.astype(np.float64, copy=True)
        if mode != "minmax":
            raise ValueError("relevance_normalization must be 'minmax' or 'none'")
        low = scores.min()
        span = scores.max() - low
        if span <= np.finfo(np.float64).eps:
            return np.ones_like(scores, dtype=np.float64)
        return (scores - low) / span

    def _fairness_bonus(self, target, exposure, position_weight):
        """Return the group bonus for the configured exposure-debt objective."""
        mode = self.config.get("fairness_mode", "normalized_debt")
        total_exposure = float(exposure.sum())

        if mode == "positive_deficit":
            if total_exposure <= np.finfo(np.float64).eps:
                exposure_share = np.zeros_like(exposure)
            else:
                exposure_share = exposure / total_exposure
            deficit = np.maximum(target - exposure_share, 0.0)
            return position_weight * deficit

        desired_after = target * (total_exposure + position_weight)
        debt = desired_after - exposure

        if mode == "cumulative_debt":
            # Original TIGERFair objective: relative cumulative debt, including
            # a negative score for groups already beyond their target.
            return np.divide(
                debt,
                target,
                out=np.full_like(debt, -np.inf),
                where=target > 0,
            )

        if mode == "normalized_debt":
            # Primary objective: bounded positive cumulative debt. This keeps
            # lambda interpretable with either three popularity groups or
            # hundreds of provider groups.
            relative_debt = np.divide(
                np.maximum(debt, 0.0),
                desired_after,
                out=np.zeros_like(debt),
                where=desired_after > 0,
            )
            return position_weight * relative_debt

        raise ValueError(
            "fairness_mode must be one of: positive_deficit, "
            "cumulative_debt, normalized_debt"
        )

    def rerank(self, ranking_score, k):
        ranking_score = np.asarray(ranking_score)
        if ranking_score.ndim != 2:
            raise ValueError("ranking_score must be a two-dimensional matrix")
        if k <= 0:
            raise ValueError("k must be positive")

        fairness_weight = float(self.config.get("lambda", 0.5))
        if fairness_weight < 0 or not np.isfinite(fairness_weight):
            raise ValueError("lambda must be finite and non-negative")
        candidate_size = self.config.get("candidate", None)
        candidate_size = None if candidate_size is None else int(candidate_size)
        if candidate_size is not None and candidate_size <= 0:
            raise ValueError("candidate must be positive")
        if candidate_size is not None and candidate_size < k:
            raise ValueError("candidate must be at least k")
        invalid_threshold = float(self.config.get("invalid_score_threshold", 1.0))

        candidates = [
            self._candidate_items(row, candidate_size, invalid_threshold)
            for row in ranking_score
        ]
        too_short = [u for u, items in enumerate(candidates) if items.size < k]
        if too_short:
            raise ValueError(
                f"{len(too_short)} users have fewer than k={k} generated candidates; "
                f"first affected user: {too_short[0]}"
            )

        candidate_groups = np.concatenate(
            [np.fromiter((self.iid2pid[int(i)] for i in items), dtype=np.int64)
             for items in candidates]
        )
        target = self._target_distribution(candidate_groups)
        exposure = self._load_initial_exposure()
        exposure[target == 0] = 0.0
        rerank_list = [None] * ranking_score.shape[0]

        order = np.arange(ranking_score.shape[0])
        seed = self.config.get("user_order_seed")
        if seed is not None:
            order = np.random.default_rng(int(seed)).permutation(order)

        for user in trange(len(order)):
            user_id = int(order[user])
            items = candidates[user_id]
            groups = np.fromiter(
                (self.iid2pid[int(item)] for item in items), dtype=np.int64
            )
            relevance = self._normalise_relevance(ranking_score[user_id, items])
            remaining = np.ones(items.size, dtype=bool)
            selected = []

            for rank in range(k):
                position_weight = 1.0 / math.log2(rank + 2.0)
                fairness_bonus = self._fairness_bonus(
                    target, exposure, position_weight
                )
                objective = relevance + fairness_weight * fairness_bonus[groups]
                objective[~remaining] = -np.inf
                chosen_idx = int(np.argmax(objective))
                chosen_item = int(items[chosen_idx])
                selected.append(chosen_item)
                remaining[chosen_idx] = False
                exposure[groups[chosen_idx]] += position_weight

            rerank_list[user_id] = np.asarray(selected, dtype=np.int64)

        self.last_exposure = exposure
        return rerank_list
